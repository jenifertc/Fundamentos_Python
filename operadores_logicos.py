# OPERADORES LOGICOS AND - OR - NOT

#AND

print(True and True)
print(True and False)
print(False and True)
print(False and False)

#OR
print(True or True)
print(True or False)
print(False or True)
print(False or False)

#NOT
print(not False)
print(not True) 

#EJERCICIO CON AND
print(5>3 and 2<4)
print(5>3 and 5<4)
print(2>3 and 2<4)
print(2>3 and 5<4)

#EJERCICIO CON OR
print(3==3 or 2>4)
print(2<=2 or 3!=3)
print(2!=2 or 5<10)
print(10<5 or 5==6)

#EJERCICIO CON NOT
print(not 2==2)
print(not 2>3)