#OPERADORES DE ASIGNACION

#ASIGNACION
x = 5
print(x)

#Asignacion con suma
x = x + 2 #ahora los implificamos a
x +=  2
print(x)

#Asignacion con resta
x = x - 3 #ahora los implificamos a
